from typing import Dict, List, Tuple


def decode(codes: List[int]) -> str:
    """把字符码数组还原为字符串。

    Args:
        codes: 字符码数组。

    Returns:
        还原后的字符串。
    """
    return "".join(chr(code) for code in codes)


